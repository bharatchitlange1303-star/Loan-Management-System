package com.loan.service;


import com.loan.model.LoanApplication;
import com.loan.repository.LoanRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;
import java.util.stream.Collectors;

@Service
public class LoanService {

    @Autowired
    private LoanRepository repository;

    // reading values from application.properties
    @Value("${loan.interest.rate}")
    private double defaultInterestRate;

    @Value("${loan.min.income}")
    private double minIncomeRequired;

    // 1. Apply for Loan & Validate Eligibility
    public LoanApplication applyForLoan(LoanApplication app) {
        if (app.getIncome() <= 0 || app.getLoanAmount() <= 0 || app.getTenureMonths() <= 0) {
            throw new IllegalArgumentException("Income, Loan Amount, and Tenure must be greater than 0");
        }

        // Predefined Eligibility Criteria: Income >= 25000 AND Loan Amount <= 10x Income
        if (app.getIncome() < minIncomeRequired || app.getLoanAmount() > (app.getIncome() * 10)) {
            app.setStatus("REJECTED (Not Eligible)");
        } else {
            app.setStatus("PENDING");
        }
        return repository.save(app);
    }

    //Method Overloading (Polymorphism) for EMI Calculation
    public double calculateMonthlyEMI(double amount, int months) {
        return calculateMonthlyEMI(amount, months, defaultInterestRate);
    }

    public double calculateMonthlyEMI(double amount, int months, double interestRate) {
        double totalInterest = (amount * interestRate * (months / 12.0)) / 100.0;
        return Math.round((amount + totalInterest) / months);
    }

    // Synchronized method + Multithreading with Runnable & Lambda
    public synchronized LoanApplication processLoanByAdmin(int id, boolean approve) {
        LoanApplication app = repository.findById(id);

        if (!approve) {
            app.setStatus("REJECTED BY ADMIN");
            return repository.save(app);
        }

        app.setStatus("APPROVED");

        // Thread + Runnable (using Lambda) to generate EMI schedule
        Runnable emiTask = () -> {
            double monthlyEmi = calculateMonthlyEMI(app.getLoanAmount(), app.getTenureMonths());
            List<String> schedule = new ArrayList<>();
            for (int i = 1; i <= app.getTenureMonths(); i++) {
                schedule.add("Month " + i + ": Rs. " + monthlyEmi + " [UNPAID]");
            }
            app.setEmiSchedule(schedule);
            System.out.println("EMI Schedule generated by Thread: " + Thread.currentThread().getName());
        };

        Thread thread = new Thread(emiTask);
        thread.start();
        try {
            thread.join(); // Wait for the thread to finish so Postman sees the result immediately
        } catch (InterruptedException e) {
            e.printStackTrace();
        }

        return repository.save(app);
    }

    // Track/Pay EMI installment
    public LoanApplication payEmi(int id, int monthNumber) {
        LoanApplication app = repository.findById(id);
        List<String> schedule = app.getEmiSchedule();
        if (monthNumber < 1 || monthNumber > schedule.size()) {
            throw new IllegalArgumentException("Invalid month number!");
        }
        String currentEntry = schedule.get(monthNumber - 1);
        schedule.set(monthNumber - 1, currentEntry.replace("[UNPAID]", "[PAID]"));
        return repository.save(app);
    }

    // Java 8 Stream API & Lambda to filter loans by status
    public List<LoanApplication> getLoansByStatus(String status) {
        return repository.findAll().stream()
                .filter(loan -> loan.getStatus().equalsIgnoreCase(status))
                .collect(Collectors.toList());
    }

    public List<LoanApplication> getAllLoans() {
        return repository.findAll();
    }

    public LoanApplication getLoanById(int id) {
        return repository.findById(id);
    }
}
